  CONVERSATION_NOT_FOUND: 'errorNotFound',
  CONVERSATION_BUSY: 'errorBusy',
  IDEMPOTENCY_CONFLICT: 'errorConflict',
  AGENT_NOT_CONFIGURED: 'errorNotConfigured',
  UPSTREAM_RATE_LIMITED: 'errorRateLimited',
  RUN_INTERRUPTED: 'errorInterrupted',
  SERVICE_BUSY: 'errorServiceBusy',
  CAPACITY_EXCEEDED: 'errorServiceBusy',
  MESSAGE_TOO_LONG: 'errorTooLong',
  FORBIDDEN: 'errorForbidden',
  ACCESS_DENIED: 'errorForbidden',
  CONVERSATION_ARCHIVED: 'errorArchived',
