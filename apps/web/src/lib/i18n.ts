export type TranslationKey = keyof typeof en;
export const catalogs: Record<Locale, Catalog> = { en, 'zh-CN': zhCN };
export const translate = (locale: Locale, key: TranslationKey) => catalogs[locale][key] ?? catalogs.en[key];
export function errorKey(code?: string): TranslationKey {
  const keys: Record<string, TranslationKey> = {
    NETWORK_ERROR: 'errorNetwork',
  VALIDATION_ERROR: 'errorValidation',
  CONVERSATION_NOT_FOUND: 'errorNotFound',
  CONVERSATION_BUSY: 'errorBusy',
  IDEMPOTENCY_CONFLICT: 'errorConflict',
  AGENT_NOT_CONFIGURED: 'errorNotConfigured',
  UPSTREAM_RATE_LIMITED: 'errorRateLimited',
  RUN_INTERRUPTED: 'errorInterrupted',
  SERVICE_BUSY: 'errorServiceBusy',
  CAPACITY_EXCEEDED: 'errorServiceBusy',
  MESSAGE_TOO_LONG: 'errorTooLong',
  FORBIDDEN: 'errorForbidden',
  ACCESS_DENIED: 'errorForbidden',
  CONVERSATION_ARCHIVED: 'errorArchived',
  NATIVE_SESSION_UNAVAILABLE: 'errorNativeSession',
  AGENT_SESSION_MISMATCH: 'errorSessionMismatch',
  OUTPUT_LIMIT_EXCEEDED: 'errorOutputLimit',
  UNAUTHORIZED: 'errorForbidden',
  RUN_TIMEOUT: 'errorTimeout',
  GENERATION_TIMEOUT: 'errorTimeout',
  UPSTREAM_ERROR: 'errorUpstream',
  AGENT_ERROR: 'errorUpstream',
  RESYNC_REQUIRED: 'errorResync',
  };
  return (code && keys[code]) || 'errorGeneric';
}
